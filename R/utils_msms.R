#' Plot a tandem mass spectrum
#'
#' @param peak_list Two-column matrix or data frame containing m/z and
#'   intensity.
#'
#' @return A `ggplot` object.
#' @export
#' @author Yaoxiang Li
plot_peak_list <- function(peak_list) {
  peaks <- .standardize_peak_list(peak_list)
  ggplot2::ggplot(
    peaks,
    ggplot2::aes(x = .data$mz, xend = .data$mz, y = 0, yend = .data$intensity)
  ) +
    ggplot2::geom_segment(linewidth = 0.4) +
    ggplot2::theme_bw() +
    ggplot2::labs(x = "m/z", y = "Relative intensity", caption = "Created by Yaoxiang Li") +
    ggplot2::theme(plot.caption = ggplot2::element_text(size = 7, hjust = 1))
}

#' Write a spectrum in MSP format
#'
#' @param file_path Output `.MSP` path.
#' @param netcdf_file Source raw-file name.
#' @param formula Molecular formula.
#' @param comments Free-text comments.
#' @param precursor_ion Precursor m/z.
#' @param precursor_type Precursor adduct.
#' @param instrument_type,instrument Instrument metadata.
#' @param peak_list Two-column matrix or data frame.
#'
#' @return Invisibly, the lines written to `file_path`.
#' @export
#' @author Yaoxiang Li
save_msp <- function(file_path,
                     netcdf_file,
                     formula = "Unknown",
                     comments = "Generated by omicsTools",
                     precursor_ion,
                     precursor_type = "Unknown",
                     instrument_type = "Unknown",
                     instrument = "Unknown",
                     peak_list) {
  peaks <- .standardize_peak_list(peak_list)
  file_name <- basename(netcdf_file)
  if (grepl("neg", file_name, ignore.case = TRUE)) {
    ion_mode <- "N"
    if (identical(precursor_type, "Unknown")) precursor_type <- "[M-H]-"
  } else if (grepl("pos", file_name, ignore.case = TRUE)) {
    ion_mode <- "P"
    if (identical(precursor_type, "Unknown")) precursor_type <- "[M+H]+"
  } else {
    ion_mode <- "Unknown"
  }
  lines <- c(
    paste0("Name: ", precursor_ion, "_", file_name),
    paste0("Formula: ", formula),
    paste0("Comments: ", comments),
    paste0("PrecursorMZ: ", precursor_ion),
    paste0("Precursor_type: ", precursor_type),
    paste0("Instrument_type: ", instrument_type),
    paste0("Instrument: ", instrument),
    paste0("Ion_mode: ", ion_mode),
    paste0("Num Peaks: ", nrow(peaks)),
    paste(format(peaks$mz, trim = TRUE), format(peaks$intensity, trim = TRUE))
  )
  dir.create(dirname(file_path), recursive = TRUE, showWarnings = FALSE)
  writeLines(lines, file_path, useBytes = TRUE)
  invisible(lines)
}

# Author: Yaoxiang Li
.standardize_peak_list <- function(peak_list) {
  peaks <- as.data.frame(peak_list, check.names = FALSE)
  if (ncol(peaks) < 2L) {
    stop("`peak_list` must contain at least two columns.", call. = FALSE)
  }
  names(peaks)[1:2] <- c("mz", "intensity")
  peaks <- peaks[c("mz", "intensity")]
  peaks$mz <- as.numeric(peaks$mz)
  peaks$intensity <- as.numeric(peaks$intensity)
  peaks[stats::complete.cases(peaks), , drop = FALSE]
}
